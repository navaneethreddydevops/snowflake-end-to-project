GRANT ALL ON ALL FUNCTIONS IN SCHEMA FAMILYBUSINESS.RAW TO ROLE &SNOWSQL_ENVVAR_ROLE;
GRANT ALL ON ALL FILE FORMATS IN SCHEMA FAMILYBUSINESS.RAW TO ROLE &SNOWSQL_ENVVAR_ROLE;
