-- Academic performance analytics view
CREATE OR REPLACE VIEW VW_ACADEMIC_PERFORMANCE_ANALYTICS AS
SELECT 
    'Overall' AS CATEGORY,
    'All Students' AS SUBCATEGORY,
    COUNT(DISTINCT s.STUDENT_ID) AS STUDENT_COUNT,
    COUNT(DISTINCT e.COURSE_ID) AS COURSE_COUNT,
    COUNT(e.ENROLLMENT_ID) AS TOTAL_ENROLLMENTS,
    ROUND(AVG(CASE WHEN e.GRADE IS NOT NULL THEN e.GRADE END), 2) AS AVERAGE_GPA,
    ROUND(AVG(CASE WHEN e.ATTENDANCE_PERCENTAGE IS NOT NULL THEN e.ATTENDANCE_PERCENTAGE END), 1) AS AVERAGE_ATTENDANCE,
    COUNT(CASE WHEN e.STATUS = 'COMPLETED' AND e.GRADE >= 3.0 THEN 1 END) AS PASSING_GRADES,
    COUNT(CASE WHEN e.STATUS = 'COMPLETED' AND e.GRADE < 2.0 THEN 1 END) AS FAILING_GRADES,
    ROUND((COUNT(CASE WHEN e.STATUS = 'DROPPED' THEN 1 END) * 100.0 / COUNT(e.ENROLLMENT_ID)), 1) AS DROP_RATE_PERCENT
FROM STUDENTS s
LEFT JOIN ENROLLMENTS e ON s.STUDENT_ID = e.STUDENT_ID

UNION ALL

SELECT 
    'By Department' AS CATEGORY,
    COALESCE(t.DEPARTMENT, 'Unknown') AS SUBCATEGORY,
    COUNT(DISTINCT e.STUDENT_ID) AS STUDENT_COUNT,
    COUNT(DISTINCT c.COURSE_ID) AS COURSE_COUNT,
    COUNT(e.ENROLLMENT_ID) AS TOTAL_ENROLLMENTS,
    ROUND(AVG(CASE WHEN e.GRADE IS NOT NULL THEN e.GRADE END), 2) AS AVERAGE_GPA,
    ROUND(AVG(CASE WHEN e.ATTENDANCE_PERCENTAGE IS NOT NULL THEN e.ATTENDANCE_PERCENTAGE END), 1) AS AVERAGE_ATTENDANCE,
    COUNT(CASE WHEN e.STATUS = 'COMPLETED' AND e.GRADE >= 3.0 THEN 1 END) AS PASSING_GRADES,
    COUNT(CASE WHEN e.STATUS = 'COMPLETED' AND e.GRADE < 2.0 THEN 1 END) AS FAILING_GRADES,
    ROUND((COUNT(CASE WHEN e.STATUS = 'DROPPED' THEN 1 END) * 100.0 / COUNT(e.ENROLLMENT_ID)), 1) AS DROP_RATE_PERCENT
FROM ENROLLMENTS e
JOIN COURSES c ON e.COURSE_ID = c.COURSE_ID
LEFT JOIN TEACHERS t ON c.TEACHER_ID = t.TEACHER_ID
WHERE t.DEPARTMENT IS NOT NULL
GROUP BY t.DEPARTMENT
COMMENT = 'Comprehensive academic performance analytics by various categories';

