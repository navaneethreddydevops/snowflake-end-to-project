-- Switch to ACCOUNTADMIN for user and role creation
USE ROLE ACCOUNTADMIN;

-- Create custom roles first
CREATE ROLE SCHOOL_BUSINESS_DB_READ_ROLE;
CREATE ROLE SCHOOL_BUSINESS_DB_READ_WRITE_ROLE;

-- Grant custom roles to SYSADMIN (best practice)
GRANT ROLE SCHOOL_BUSINESS_DB_READ_ROLE TO ROLE SYSADMIN;
GRANT ROLE SCHOOL_BUSINESS_DB_READ_WRITE_ROLE TO ROLE SYSADMIN;

-- Switch to SYSADMIN for database and warehouse creation
USE ROLE SYSADMIN;

CREATE DATABASE SCHOOL_BUSINESS_DB;
USE DATABASE SCHOOL_BUSINESS_DB; 
CREATE SCHEMA SCHOOL_BUSINESS_SCHEMA;

-- Create a warehouse for the school business operations
CREATE WAREHOUSE SCHOOL_BUSINESS_WH WITH
    WAREHOUSE_SIZE = 'X-SMALL'
    AUTO_SUSPEND = 300
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

-- Switch back to ACCOUNTADMIN for user creation
USE ROLE ACCOUNTADMIN;
CREATE USER SCHOOL_BUSINESS_DB_READ_USER PASSWORD='ReadUserPass123' DEFAULT_ROLE=SCHOOL_BUSINESS_DB_READ_ROLE DEFAULT_WAREHOUSE=SCHOOL_BUSINESS_WH;
CREATE USER SCHOOL_BUSINESS_DB_READ_WRITE_USER PASSWORD='ReadWriteUserPass123' DEFAULT_ROLE=SCHOOL_BUSINESS_DB_READ_WRITE_ROLE DEFAULT_WAREHOUSE=SCHOOL_BUSINESS_WH;
GRANT ROLE SCHOOL_BUSINESS_DB_READ_ROLE TO USER SCHOOL_BUSINESS_DB_READ_USER;
GRANT ROLE SCHOOL_BUSINESS_DB_READ_WRITE_ROLE TO USER SCHOOL_BUSINESS_DB_READ_WRITE_USER;
GRANT ROLE SCHOOL_BUSINESS_DB_READ_ROLE TO ROLE SCHOOL_BUSINESS_DB_READ_WRITE_ROLE;

-- Switch to SYSADMIN for table creation
USE ROLE SYSADMIN;
USE DATABASE SCHOOL_BUSINESS_DB;
USE SCHEMA SCHOOL_BUSINESS_SCHEMA;
CREATE TABLE STUDENTS (
    STUDENT_ID INT PRIMARY KEY,
    FIRST_NAME VARCHAR(50) NOT NULL,
    LAST_NAME VARCHAR(50) NOT NULL,
    DATE_OF_BIRTH DATE NOT NULL,
    EMAIL VARCHAR(100) UNIQUE NOT NULL,
    PHONE_NUMBER VARCHAR(15),
    ADDRESS VARCHAR(255),
    ENROLLMENT_DATE DATE NOT NULL
);
CREATE TABLE TEACHERS (
    TEACHER_ID INT PRIMARY KEY,
    FIRST_NAME VARCHAR(50) NOT NULL,
    LAST_NAME VARCHAR(50) NOT NULL,
    EMAIL VARCHAR(100) UNIQUE NOT NULL,
    PHONE_NUMBER VARCHAR(15),
    HIRE_DATE DATE NOT NULL,
    SUBJECT VARCHAR(100) NOT NULL
);
CREATE TABLE COURSES (
    COURSE_ID INT PRIMARY KEY,
    COURSE_NAME VARCHAR(100) NOT NULL,
    DESCRIPTION TEXT,
    CREDITS INT NOT NULL,
    TEACHER_ID INT,
    FOREIGN KEY (TEACHER_ID) REFERENCES TEACHERS(TEACHER_ID)
);
CREATE TABLE ENROLLMENTS (
    ENROLLMENT_ID INT PRIMARY KEY,
    STUDENT_ID INT,
    COURSE_ID INT,
    ENROLLMENT_DATE DATE NOT NULL,
    GRADE DECIMAL(3, 2),
    FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID),
    FOREIGN KEY (COURSE_ID) REFERENCES COURSES(COURSE_ID)
);

