-- Grant permissions (SYSADMIN can grant on objects it owns)
-- Grant database usage to both roles
GRANT USAGE ON DATABASE SCHOOL_BUSINESS_DB TO ROLE SCHOOL_BUSINESS_DB_READ_ROLE;
GRANT USAGE ON DATABASE SCHOOL_BUSINESS_DB TO ROLE SCHOOL_BUSINESS_DB_READ_WRITE_ROLE;

-- Grant warehouse usage to both roles
GRANT USAGE ON WAREHOUSE SCHOOL_BUSINESS_WH TO ROLE SCHOOL_BUSINESS_DB_READ_ROLE;
GRANT USAGE ON WAREHOUSE SCHOOL_BUSINESS_WH TO ROLE SCHOOL_BUSINESS_DB_READ_WRITE_ROLE;

-- Grant OPERATE privilege on warehouse (allows starting/stopping the warehouse)
GRANT OPERATE ON WAREHOUSE SCHOOL_BUSINESS_WH TO ROLE SCHOOL_BUSINESS_DB_READ_ROLE;
GRANT OPERATE ON WAREHOUSE SCHOOL_BUSINESS_WH TO ROLE SCHOOL_BUSINESS_DB_READ_WRITE_ROLE;

-- Grant schema usage and permissions
GRANT USAGE ON SCHEMA SCHOOL_BUSINESS_SCHEMA TO ROLE SCHOOL_BUSINESS_DB_READ_ROLE;
GRANT USAGE ON SCHEMA SCHOOL_BUSINESS_SCHEMA TO ROLE SCHOOL_BUSINESS_DB_READ_WRITE_ROLE;

-- Grant table permissions to READ_ROLE
GRANT SELECT ON ALL TABLES IN SCHEMA SCHOOL_BUSINESS_SCHEMA TO ROLE SCHOOL_BUSINESS_DB_READ_ROLE;

-- Grant table permissions to READ_WRITE_ROLE
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA SCHOOL_BUSINESS_SCHEMA TO ROLE SCHOOL_BUSINESS_DB_READ_WRITE_ROLE;

-- Grant schema-level permissions to READ_WRITE_ROLE
GRANT CREATE TABLE ON SCHEMA SCHOOL_BUSINESS_SCHEMA TO ROLE SCHOOL_BUSINESS_DB_READ_WRITE_ROLE;
GRANT CREATE VIEW ON SCHEMA SCHOOL_BUSINESS_SCHEMA TO ROLE SCHOOL_BUSINESS_DB_READ_WRITE_ROLE;
GRANT CREATE STAGE ON SCHEMA SCHOOL_BUSINESS_SCHEMA TO ROLE SCHOOL_BUSINESS_DB_READ_WRITE_ROLE;
GRANT CREATE PIPE ON SCHEMA SCHOOL_BUSINESS_SCHEMA TO ROLE SCHOOL_BUSINESS_DB_READ_WRITE_ROLE;





